/**
 * The interstate network of Career and the Daily Haul: freight hubs joined
 * by real corridors, each a waypoint table in the original's own notation.
 * A row is the mile from the corridor's first hub, the place, the road that
 * leads there, and codes as in the original's DATA lines: 2.xx a toll of xx
 * dollars, 3.xx construction, 4.xx radar, 5.xx a scale, 6.xx a rock slide,
 * 7.xx reefer trouble, the fraction being the odds that nothing happens.
 * Time zones are not coded: the planner reads them off the map.
 *
 * Mileages follow the interstates of the early 1980s, rounded to five
 * miles or so. The limit is the national 55 everywhere, as it was.
 */
export type CorridorRow = readonly [
  mile: number,
  place: string,
  road: string,
  codes?: number | readonly number[],
];

export interface CorridorSpec {
  id: string;
  from: string;
  to: string;
  /** The interstates it follows, for the route cards. */
  roads: string;
  /** RH: the original's 4 for the north, 2 for the middle, 1 for the south. */
  factor: number;
  /** RT in the fine formula: 1 north, 0 middle, 2 south. */
  fineBase: number;
  rows: readonly CorridorRow[];
  /** Tolls taken only going one way, by place: into New York, into San Francisco. */
  oneWayTolls?: Readonly<Record<string, 'forward' | 'backward'>>;
  /** Rock slides that only threaten one way, by place: the tunnel lies ahead of it. */
  oneWaySlides?: Readonly<Record<string, 'forward' | 'backward'>>;
  /** Where each rock slide happens, by place. */
  slideNames?: Readonly<Record<string, string>>;
}

